//! ONNX: the preflight every model in a bundle passes, and inference.
//!
//! - [`preflight`]: valid ONNX, opset in range, no external data or custom
//!   operators, a static graph whose every tensor has a constant size,
//!   operators on the allowlist, each call's charge within a turn's budget
//!   and the memory bound. It computes the charge from the graph as given,
//!   before ONNX Runtime optimises anything.
//! - [`policy`]: the extra checks a trained policy's model passes against its
//!   arena's declaration (the shell's ONNX contract).
//! - [`runtime`]: a seat's models on ONNX Runtime, single-threaded, with the
//!   memory arena and pattern planning off and denormals flushed to zero.

pub mod policy;
pub mod preflight;
pub mod runtime;

/// The ONNX protobuf types, generated by prost from `onnx.proto` (ONNX's own,
/// Apache-2.0, v1.18.0, beside this file) and committed, so nothing needs
/// `protoc` to build.
#[allow(clippy::all, missing_docs)]
pub mod proto {
    include!("proto_gen.rs");
}

pub use preflight::{ModelInfo, TensorInfo, preflight};
